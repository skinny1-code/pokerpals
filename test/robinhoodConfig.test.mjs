import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
const read = (file) => readFileSync(new URL('../' + file, import.meta.url), 'utf8');
const hardhat = read('hardhat.config.js');
const deploy = read('scripts/deploy.js');
const faucet = read('scripts/faucet.js');
const wallet = read('src/hooks/wallet/core.js');
const token = read('contracts/ChipsToken.sol');
const buy = read('src/app/buy/page.jsx');
assert.match(hardhat, /robinhoodTestnet:[\\s\\S]*chainId: 46630/);
assert.match(hardhat, /robinhood:[\\s\\S]*chainId: 4663/);
assert.match(wallet, /id: 46630/);
assert.match(wallet, /id: 4663/);
assert.match(wallet, /\\[arbitrum, arbitrumSepolia, robinhoodTestnet, robinhoodChain\\]/);
assert.match(deploy, /ROBINHOOD_MAINNET_DEPLOY_ACK/);
assert.match(deploy, /ROBINHOOD_USDC_ADDRESS/);
assert.match(deploy, /networkName === "robinhoodTestnet"/);
assert.match(faucet, /\\[421614, 46630\\]/);
assert.match(buy, /tab === 'card' && !IS_ROBINHOOD/);
assert.match(token, /ERC20\\("PokerChips", "CHIPS"\\)/);
assert.match(token, /1_000_000_000 \\* 10\\*\\*18/);
console.log('Robinhood network and existing-CHIPS safety invariants verified (source-level only).');
